import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const destination = resolve(import.meta.dir, "../lib/bun/vendor");
const result = await Bun.build({
  entrypoints: [resolve(import.meta.dir, "html-tokenizer-entry.ts")],
  target: "bun",
  format: "esm",
  minify: true,
  banner: "// Generated by npm run build:html-tokenizer. Licenses: html-tokenizer.LICENSE",
});
if (!result.success) throw new AggregateError(result.logs, "HTML tokenizer を bundle できません");
mkdirSync(destination, { recursive: true });
writeFileSync(resolve(destination, "html-tokenizer.js"), await result.outputs[0]!.text());
writeFileSync(
  resolve(destination, "html-tokenizer.LICENSE"),
  ["htmlparser2", "entities"]
    .map(
      (name) =>
        `${name}\n\n${readFileSync(resolve(import.meta.dir, "node_modules", name, "LICENSE"), "utf8")}`,
    )
    .join("\n")
    .replace(/[ \t]+$/gm, ""),
);
